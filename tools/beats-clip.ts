#!/usr/bin/env node
// tools/beats clip: an ad's window onto a track's measured beat map, as a TypeScript module both
// the picture (index.tsx) and the designed sound (sound.ts, run by Node) import.
//
//   tools/beats clip <music-id> --from <sec> --length <sec> [--fps 60] [--out ads/<ad>/beatmap.ts]
//
// --from: seconds into the track file at frame 0 (pick a downbeat: the clip prints the nearest).
// Needs the track's beatMap in its manifest (tools/beats <music-id> --write).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { AdBeatMap } from "../motion/beatmap.ts";
import { INDEX_PATH, parseArgs, readJson, ROOT } from "./lib/core.ts";

type Map = { bpm: number; beats: number[]; downbeats: number[]; hits: [number, number][]; bars: number[]; sections: { t: number; kind: string; db: number }[] };
const args = parseArgs(process.argv.slice(2));
const id = args._[0];
const from = Number(args.from);
const len = Number(args.length);
const fps = Number(args.fps ?? 60);
if (!id || !Number.isFinite(from) || !Number.isFinite(len)) {
  console.log("usage: tools/beats clip <music-id> --from <sec> --length <sec> [--fps 60] [--out ads/<ad>/beatmap.ts]");
  process.exit(1);
}
const e = readJson<{ assets: { id: string; asset: { beatMap?: Map } }[] }>(INDEX_PATH).assets.find((a) => a.id === id);
if (!e) throw new Error(`${id}: not in the catalog`);
const bm = e.asset.beatMap;
if (!bm) throw new Error(`${id}: no beatMap yet. Run: tools/beats ${id} --write`);
const r3 = (x: number) => Math.round(x * 1000) / 1000;
const inside = (t: number) => t >= from - 1e-3 && t < from + len - 1e-3;
const rel = (t: number) => r3(Math.max(0, t - from));
const nearDown = bm.downbeats.reduce((a, b) => (Math.abs(b - from) < Math.abs(a - from) ? b : a), bm.downbeats[0]);
const out: AdBeatMap = {
  track: id,
  fromSec: from,
  lengthSec: len,
  fps,
  bpm: bm.bpm,
  beats: bm.beats.filter(inside).map(rel),
  downbeats: bm.downbeats.filter(inside).map(rel),
  hits: bm.hits.filter(([t]) => inside(t)).map(([t, s]) => [rel(t), s]),
  bars: bm.downbeats.map((t, i) => ({ t, db: bm.bars[i] })).filter((b) => inside(b.t)).map((b) => ({ t: rel(b.t), db: b.db })),
  sections: bm.sections.filter((s) => inside(s.t)).map((s) => ({ ...s, t: rel(s.t) })),
};
const ts = `// GENERATED by \`tools/beats clip ${id} --from ${from} --length ${len} --fps ${fps}\` from the track's
// measured beat map (catalog: ${id} › beatMap, ${bm.bpm} BPM). Don't hand-edit: re-run the clip.
// Times are seconds from frame 0 of the ad. Read it with motion/beatmap.ts › beatClockOf().
import type { AdBeatMap } from "../../motion/beatmap.ts";

export const BEATMAP: AdBeatMap = ${JSON.stringify(out)};
`;
if (typeof args.out === "string") {
  writeFileSync(join(ROOT, args.out), ts);
  console.log(`wrote ${args.out}`);
}
console.log(`${id} from ${from} s for ${len} s: ${out.beats.length} beats, ${out.downbeats.length} downbeats, ${out.hits.length} hits at ${bm.bpm} BPM`);
if (Math.abs(nearDown - from) > 0.002) console.log(`note: --from is ${r3(from - nearDown)} s off the nearest downbeat (${nearDown} s)`);
console.log(`downbeats (s from frame 0): ${out.downbeats.join(", ")}`);
console.log(`sections inside: ${out.sections.map((s) => `${s.kind} ${s.t}s (${s.db} dB)`).join(", ") || "none"}`);
