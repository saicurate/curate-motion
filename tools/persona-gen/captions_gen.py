"""ads/skit-chopped/captions.ts from the script's words + whisper word times (.cache/persona-gen/jake/vo/words.json).
Display words come from script.json (exact text); times from whisper, aligned with difflib; gaps interpolated."""
import difflib, json, re, sys
ROOT = "/Users/saikumar/Desktop/Curate/curate-motion"
script = json.load(open(f"{ROOT}/ads/skit-chopped/script.json"))
words = json.load(open(f"{ROOT}/.cache/persona-gen/jake/vo/words.json"))
norm = lambda w: re.sub(r"[^a-z0-9']", "", w.lower().replace("’", "'"))
out = {}
for line in script["lines"]:
    lid = line["id"]
    ww = words[f"{lid}-eleven-will-v4.v1.mp3"]
    toks = line["text"].split()
    a = [norm(t) for t in toks]; b = [norm(w[0]) for w in ww]
    times = [None] * len(toks)
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1): times[i1 + k] = (ww[j1 + k][1], ww[j1 + k][2])
        elif tag == "replace" and j2 > j1:
            s, e = ww[j1][1], ww[j2 - 1][2]
            n = i2 - i1
            for k in range(n): times[i1 + k] = (s + (e - s) * k / n, s + (e - s) * (k + 1) / n)
    # fill any left gaps by interpolation between neighbours
    for i, t in enumerate(times):
        if t is None:
            prev = next((times[j][1] for j in range(i - 1, -1, -1) if times[j]), 0.0)
            nxt = next((times[j][0] for j in range(i + 1, len(times)) if times[j]), ww[-1][2])
            times[i] = (prev, max(prev + 0.05, nxt))
    out[lid] = [[tok, round(s, 3), round(e, 3)] for tok, (s, e) in zip(toks, times)]
ts = ("// Generated by tools/persona-gen/captions_gen.py: each line's words (script.json text) with their times in the ORIGINAL\n"
      "// clip (whisper base.en, local). The ad divides by RATE and adds LINE_AT. Do not edit by hand.\n"
      "export const WORDS: Record<string, [string, number, number][]> = " + json.dumps(out, indent=0, ensure_ascii=False) + ";\n")
open(f"{ROOT}/ads/skit-chopped/captions.ts", "w").write(ts)
for k, v in out.items(): print(k, " ".join(f"{w}@{s:.2f}" for w, s, e in v))
