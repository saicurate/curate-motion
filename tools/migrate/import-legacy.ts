#!/usr/bin/env node
// tools/migrate/import-legacy.ts: COPY marketing/videos/ (and the Zee pack) into library/ with
// manifests, ids, sha256, dims and licences. Never moves or deletes anything at the source.
//
//   node tools/migrate/import-legacy.ts            dry run: prints the plan and every problem
//   node tools/migrate/import-legacy.ts --apply    copies files, writes manifests, rebuilds the catalog
//   [--src <marketing/videos>] [--zee <zee-sharp-v1 dir>] [--only brand,zee,garments,people,roll,stock,music,references,footage,renders]
//
// Provenance that only lived in prose (who picked what, BPMs found while cutting) is written into
// the manifests here, with a note saying where it came from. Everything lands as status "draft"
// except what the founder explicitly decided (Emma's face B picked, A and C kept but not used).
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { Asset } from "../../schemas/asset.ts";
import { LIB, parseArgs, probe, readJson, ROOT, sha256File, treeSha, writeJson } from "../lib/core.ts";

const args = parseArgs(process.argv.slice(2));
const APPLY = !!args.apply;
const SRC = String(args.src ?? join(ROOT, "..", "marketing", "videos"));
const ZEE_PACK = String(args.zee ?? join(ROOT, "..", "research", "zee-pack", "app", "zee-sharp-v1"));
const ONLY = typeof args.only === "string" ? args.only.split(",") : null;
const on = (k: string) => !ONLY || ONLY.includes(k);
const DAY = "2026-10-15";
const BY = { type: "agent", name: "import-legacy", note: "migrated from marketing/videos", at: new Date().toISOString().slice(0, 10) };

const problems: string[] = [];
const copies: [string, string][] = [];
const manifests = new Map<string, { about: string; assets: Record<string, unknown>[] }>();

const S = (...p: string[]) => join(SRC, ...p);
/** Plan a copy src -> library/<rel>; returns a FileRef (hashing the SOURCE, so a dry run is exact). */
const file = (src: string, rel: string, role = "original") => {
  if (!existsSync(src)) {
    problems.push(`missing source ${src}`);
    return null;
  }
  copies.push([src, join(LIB, rel)]);
  return { role, path: rel, sha256: sha256File(src), bytes: statSync(src).size, mime: probe(src).mime };
};
const dimsOf = (src: string) => {
  const p = probe(src);
  return p.w && p.h ? { w: p.w, h: p.h } : undefined;
};
const push = (manifestRel: string, about: string, rec: Record<string, unknown>) => {
  const r = Asset.safeParse(rec);
  if (!r.success) {
    problems.push(`${rec.id}: ${r.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
    return;
  }
  const m = manifests.get(manifestRel) ?? { about, assets: [] };
  m.assets.push(r.data as unknown as Record<string, unknown>);
  manifests.set(manifestRel, m);
};
const tags = (t: Partial<{ persona: string; moment: string; mood: string[]; colour: string[]; season: string[]; free: string[] }> = {}) => ({ mood: [], colour: [], season: [], free: [], ...t });
const kebab = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

const CURATE = { name: "Curate original", commercial: true, restrictions: [], checkedAt: DAY };
const AI_OWNED = (model: string) => ({ name: "AI-generated, Curate-owned output", commercial: true, restrictions: ["no-real-person-likeness", "persona-never-vouches-for-products"], proof: `Generated by Curate with ${model}; output owned by the user under the provider's terms.`, checkedAt: DAY });

// ---------------------------------------------------------------- brand + fonts
if (on("brand")) {
  const B = S("remotion", "public", "brand");
  for (const [f, name, title] of [
    ["splash_logo.png", "logo-splash", "Curate logo (splash lockup)"],
    ["logo_mark.png", "logo-mark", "Curate mark"],
    ["splash_mark.png", "splash-mark", "Curate splash mark"],
  ]) {
    const fr = file(join(B, f), `brand/curate/${name}.v1.png`);
    if (fr) push("brand/manifest.json", "Curate's own brand marks and typefaces (from curate-app).", { id: `brand.curate.${name}.v1`, kind: "brand", title, files: [fr], dims: dimsOf(join(B, f)), tags: tags(), source: { type: "original", url: "curate-app/assets", from: [] }, licence: CURATE, createdBy: BY, status: "draft", aiGenerated: false });
  }
  const F = S("remotion", "public", "fonts");
  for (const [f, w] of [["Geist-Regular.ttf", 400], ["Geist-Medium.ttf", 500], ["Geist-SemiBold.ttf", 600]] as const) {
    const name = kebab(f.replace(/\.ttf$/, "").replace("Geist-", ""));
    const fr = file(join(F, f), `brand/fonts/geist-${name}.v1.ttf`);
    if (fr)
      push("brand/manifest.json", "Curate's own brand marks and typefaces (from curate-app).", {
        id: `font.geist.${name}.v1`, kind: "font", title: `Geist ${f.replace(/\.ttf$/, "").replace("Geist-", "")}`, family: "Geist", weight: w, files: [fr], tags: tags(),
        source: { type: "stock", author: "Vercel", url: "https://github.com/vercel/geist-font", from: [] },
        licence: { name: "SIL Open Font License 1.1", url: "https://github.com/vercel/geist-font/blob/main/LICENSE.TXT", commercial: true, restrictions: ["do-not-sell-the-font-alone"], checkedAt: DAY },
        createdBy: BY, status: "draft", aiGenerated: false,
      });
  }
}

// ---------------------------------------------------------------- Zee
if (on("zee")) {
  const Z = S("remotion", "public", "zee");
  if (!existsSync(Z)) problems.push(`missing ${Z}`);
  else
    for (const emo of readdirSync(Z).filter((d) => statSync(join(Z, d)).isDirectory()).sort()) {
      for (const part of ["intro", "loop", "outro"]) {
        const d = join(Z, emo, part);
        if (!existsSync(d)) continue;
        const t = treeSha(d);
        const names = readdirSync(d).filter((n) => !n.startsWith("."));
        for (const n of names) copies.push([join(d, n), join(LIB, "zee", emo, `${part}.v1`, n)]);
        const packFile = join(ZEE_PACK, `${emo}-a-${part}.webp`);
        const fr = file(packFile, `zee/${emo}/${part}.v1.webp`);
        if (!fr) continue;
        push("zee/manifest.json", "Zee, Curate's black plush kitten: 720 px frame sequences from the zee-sharp-v1 pack (Blender renders), one asset per emotion part.", {
          id: `zee.${emo}.${part}.v1`, kind: "zee", title: `Zee ${emo}, ${part}`, emotion: emo, part, pack: "zee-sharp-v1",
          dims: dimsOf(join(d, names.sort()[0])), frames: { dir: `zee/${emo}/${part}.v1`, pattern: "%04d.webp", count: t.count, fps: 30, treeSha256: t.sha256, bytes: t.bytes },
          files: [fr], tags: tags({ mood: [emo] }),
          source: { type: "rendered", tool: "Blender; frames converted by marketing/videos/tools/zee_frames.py", url: "research/zee-pack/zee-v2/sharp/frames-720-f18cL-v2", from: [] },
          licence: { ...CURATE, name: "Curate original (Curate's character)" }, createdBy: BY, status: "draft", aiGenerated: false,
        });
      }
      const still = join(ZEE_PACK, `${emo}-a.png`);
      const fr = file(still, `zee/${emo}/still.v1.png`);
      if (fr) push("zee/manifest.json", "", { id: `zee.${emo}.still.v1`, kind: "zee", title: `Zee ${emo}, still`, emotion: emo, part: "still", pack: "zee-sharp-v1", dims: dimsOf(still), files: [fr], tags: tags({ mood: [emo] }), source: { type: "rendered", tool: "Blender", from: [] }, licence: { ...CURATE, name: "Curate original (Curate's character)" }, createdBy: BY, status: "draft", aiGenerated: false });
    }
}

